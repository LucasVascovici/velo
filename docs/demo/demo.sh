#!/usr/bin/env bash
# Regenerates docs/demo/transcript.md: a scripted session in which an agent
# run goes wrong and the history shows how.
#
#   docs/demo/demo.sh path/to/velody
#
# Unix only (bash, sed, mktemp). CI runs it on Linux and fails when the
# committed transcript differs from what this script writes.
#
# The output must be byte-identical between runs, so every value that varies
# is rewritten to fixed text before it reaches the transcript: snapshot ids,
# times, durations, the temporary directory and the author's local settings.

set -euo pipefail

if [ $# -ne 1 ] || [ ! -x "$1" ]; then
    echo "usage: $0 path/to/velody" >&2
    exit 2
fi

HERE=$(cd "$(dirname "$0")" && pwd)
VELO=$(cd "$(dirname "$1")" && pwd)/$(basename "$1")
OUT="$HERE/transcript.md"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

export NO_COLOR=1 TZ=UTC LC_ALL=C
export VELODY_AUTHOR_NAME="Dana Developer" VELODY_AUTHOR_EMAIL="dana@example.com"
# A throwaway home, so nothing from the machine's own configuration leaks in.
export HOME="$WORK/home"
mkdir -p "$HOME"

REPO="$WORK/repo"
mkdir -p "$REPO"
cd "$REPO"

# Rewrites whatever varies between runs. The ids keep their length so the
# columns still line up; each distinct id gets a stable letter, in the order
# it first appears.
normalise() {
    sed -E \
        -e "s#$WORK#/tmp/demo#g" \
        -e 's#in [^ ]*[/\\]repo[/\\]\.velo#in /tmp/demo/repo/.velo#' \
        -e 's#[0-9]{4}-[0-9]{2}-[0-9]{2}[T ][0-9]{2}:[0-9]{2}(:[0-9]{2})?(\.[0-9]+)?(Z| ?\+00:00| UTC)?#2025-01-06 09:00#g' \
        -e 's#[0-9]+(\.[0-9]+)? ?(ms|µs|s) #<time> #g' \
        -e 's#[0-9]+ (second|minute|hour|day|week)s? ago#<ago>#g'
}

# Short ids are replaced by labels: the first distinct id seen becomes
# <snap-1>, the next <snap-2>, and so on. The map lives in a file because
# each step runs in its own pipeline.
IDS="$WORK/ids"
: > "$IDS"
label_ids() {
    local line id n
    while IFS= read -r line; do
        for id in $(printf '%s\n' "$line" | grep -oE '\b[0-9a-f]{7,64}\b' | grep -E '[0-9]' || true); do
            if ! grep -qx "$id" "$IDS"; then
                echo "$id" >> "$IDS"
            fi
            n=$(grep -nx "$id" "$IDS" | head -n1 | cut -d: -f1)
            line=${line//$id/<snap-$n>}
        done
        printf '%s\n' "$line"
    done
}

: > "$OUT"
say() { printf '%s\n' "$*" >> "$OUT"; }

# step 'save "message"' runs `velody save "message"` and records the command
# and its output as one fenced block. A step may fail on purpose, so its exit
# status is not checked here; the story's own checks below catch a real break.
step() {
    say '```console'
    printf '$ velody %s\n' "$1" | label_ids >> "$OUT"
    eval "\"\$VELO\" $1" > "$WORK/last" 2>&1 || true
    normalise < "$WORK/last" | label_ids >> "$OUT"
    say '```'
    say ''
}

# The id the last `velody save` printed, so a later step can name it.
saved_id() { sed -nE 's/.*Saved ([0-9a-f]+) .*/\1/p' "$WORK/last"; }

# Edits the working tree without recording a command (the agent's tool call).
note() { say "$*"; say ''; }

say '# Demo: an agent run went wrong'
say ''
say 'This transcript is generated by [`demo.sh`](demo.sh) and checked in CI, so it'
say 'is always what the current `velody` prints. Ids and times are replaced by'
say 'fixed text; see the [README](./).'
say ''

note '## A human saves the base'

step 'init'
cat > app.py <<'EOF'
def total(xs):
    return sum(xs)


def average(xs):
    return total(xs) / len(xs)


print(average([1, 2, 3]))
EOF
cat > test_app.py <<'EOF'
from app import average

assert average([1, 2, 3]) == 2
EOF
step 'save "Base: total and average"'

note '## The agent works, one snapshot per tool call'
note 'The agent runs under its own author name, so every snapshot says who made it.'

export VELODY_AUTHOR_NAME="agent-run-7" VELODY_AUTHOR_EMAIL="agent@example.com"

cat >> test_app.py <<'EOF'
assert average([4]) == 4
EOF
step 'save "run-7 call 1: add a one-element test"'

cat > app.py <<'EOF'
def total(xs):
    return sum(xs)


def average(xs):
    return total(xs) / len(xs)


def largest(xs):
    return max(xs)


print(average([1, 2, 3]))
EOF
step 'save "run-7 call 2: add largest"'

# The bad change: a "tidy-up" that drops the total and divides by the wrong
# length, so average([1, 2, 3]) is no longer 2.
cat > app.py <<'EOF'
def total(xs):
    return sum(xs)


def average(xs):
    return total(xs) / (len(xs) + 1)


def largest(xs):
    return max(xs)


print(average([1, 2, 3]))
EOF
step 'save "run-7 call 3: tidy up average"'
BAD=$(saved_id)

export VELODY_AUTHOR_NAME="Dana Developer" VELODY_AUTHOR_EMAIL="dana@example.com"

note '## The tests fail; the history shows why'
note 'Start with who did what, newest first.'
step 'history'

note 'The failing function is `average`. Find the snapshot that last touched its line.'
step 'blame app.py --lines 5-6'

note 'Blame names a snapshot made by the agent. `show` prints that one change against its parent.'
step "show $BAD"

note '## Recovery'
note 'Undo removes the bad snapshot and puts the tree back. The earlier calls stay.'
step 'undo'
step 'history'
step 'status'

note '## The audit report'
note 'Everything above is also available as one offline HTML file.'
step 'report -o report.html'

# The report names the repository path and the time it was made, so this one
# is not checked in; docs/report-sample.html is the checked-in sample.
test -s report.html
note 'A finished report for a similar run is checked in as [`report-sample.html`](../report-sample.html); open it in any browser, offline.'
